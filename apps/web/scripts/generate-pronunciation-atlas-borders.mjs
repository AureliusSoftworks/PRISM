import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ADMIN0_URL =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_boundary_lines_land.geojson";
const ADMIN1_URL =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_1_states_provinces_lines.geojson";
/** Match the earth mask's frame exactly so both layers stay georeferenced. */
const WIDTH = 1774;
const HEIGHT = 887;
/** State and province lines ship only where the Accent Map has deep lenses. */
const ADMIN1_COUNTRIES = new Set(["USA", "CAN"]);

function projectedPoint(longitudeDegrees, latitudeDegrees) {
  return {
    x: ((longitudeDegrees + 180) / 360) * WIDTH,
    y: ((90 - latitudeDegrees) / 180) * HEIGHT,
  };
}

function coordinate(value) {
  return Number(value.toFixed(2)).toString();
}

function lineStrings(geometry) {
  if (!geometry) return [];
  if (geometry.type === "LineString") return [geometry.coordinates];
  if (geometry.type === "MultiLineString") return geometry.coordinates;
  return [];
}

function pathData(features) {
  const paths = [];
  for (const feature of features) {
    for (const line of lineStrings(feature.geometry)) {
      const commands = [];
      for (const [longitude, latitude] of line) {
        const point = projectedPoint(longitude, latitude);
        commands.push(
          `${commands.length === 0 ? "M" : "L"}${coordinate(point.x)} ${coordinate(point.y)}`,
        );
      }
      if (commands.length > 1) paths.push(commands.join(""));
    }
  }
  return paths.join("");
}

async function fetchFeatures(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Natural Earth download failed (${response.status}).`);
  }
  const collection = await response.json();
  if (!Array.isArray(collection.features)) {
    throw new Error("Natural Earth boundary payload has no features.");
  }
  return collection.features;
}

const [admin0, admin1] = await Promise.all([
  fetchFeatures(ADMIN0_URL),
  fetchFeatures(ADMIN1_URL),
]);
// Verified international boundaries only — disputed lines and lines of
// control stay out of the sanctum's map.
const countryFeatures = admin0.filter((feature) =>
  String(feature.properties?.FEATURECLA ?? "").startsWith(
    "International boundary",
  ),
);
const stateFeatures = admin1.filter((feature) =>
  ADMIN1_COUNTRIES.has(feature.properties?.ADM0_A3),
);
const countries = pathData(countryFeatures);
const states = pathData(stateFeatures);
if (!countries || !states) {
  throw new Error("Natural Earth boundary lines are empty.");
}

const targetPath = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "public",
  "voice",
  "pronunciation-atlas-borders-equirectangular-v1.svg",
);
/**
 * The file is consumed as a CSS luminance mask: country borders render at
 * full strength, state and province lines dimmer. Non-scaling strokes keep
 * every line one device pixel wide at any lens zoom.
 */
const output = `<!-- Generated by apps/web/scripts/generate-pronunciation-atlas-borders.mjs.
Source: Natural Earth 1:50m admin-0 boundary lines and admin-1 state/province lines (USA, CAN), public domain.
Projection: equirectangular, longitude -180..180 and latitude 90..-90, matching the earth mask frame. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" preserveAspectRatio="none">
  <path fill="none" stroke="#999" stroke-width="1" vector-effect="non-scaling-stroke" stroke-linejoin="round" stroke-linecap="round" d="${states}"/>
  <path fill="none" stroke="#fff" stroke-width="1" vector-effect="non-scaling-stroke" stroke-linejoin="round" stroke-linecap="round" d="${countries}"/>
</svg>
`;

writeFileSync(targetPath, output, "utf8");
console.log(
  `Wrote ${countryFeatures.length} country and ${stateFeatures.length} state boundary features to ${targetPath}`,
);
