import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { unzipSync } from "fflate";

const SOURCE_URL =
  "https://naturalearth.s3.amazonaws.com/50m_physical/ne_50m_land.zip";
const WIDTH = 1774;
const HEIGHT = 887;

function projectedPoint(longitudeDegrees, latitudeDegrees) {
  return {
    x: ((longitudeDegrees + 180) / 360) * WIDTH,
    y: ((90 - latitudeDegrees) / 180) * HEIGHT,
  };
}

function coordinate(value) {
  return Number(value.toFixed(2)).toString();
}

function polygonPaths(shapefile) {
  const view = new DataView(
    shapefile.buffer,
    shapefile.byteOffset,
    shapefile.byteLength,
  );
  const paths = [];
  let recordOffset = 100;

  while (recordOffset + 8 <= shapefile.byteLength) {
    const contentBytes = view.getInt32(recordOffset + 4, false) * 2;
    const contentOffset = recordOffset + 8;
    const recordEnd = contentOffset + contentBytes;
    if (contentBytes <= 0 || recordEnd > shapefile.byteLength) break;

    const shapeType = view.getInt32(contentOffset, true);
    if (shapeType === 5 || shapeType === 15 || shapeType === 25) {
      const partCount = view.getInt32(contentOffset + 36, true);
      const pointCount = view.getInt32(contentOffset + 40, true);
      const partsOffset = contentOffset + 44;
      const pointsOffset = partsOffset + partCount * 4;

      for (let partIndex = 0; partIndex < partCount; partIndex += 1) {
        const start = view.getInt32(partsOffset + partIndex * 4, true);
        const end =
          partIndex + 1 < partCount
            ? view.getInt32(partsOffset + (partIndex + 1) * 4, true)
            : pointCount;
        const commands = [];

        for (let pointIndex = start; pointIndex < end; pointIndex += 1) {
          const pointOffset = pointsOffset + pointIndex * 16;
          const point = projectedPoint(
            view.getFloat64(pointOffset, true),
            view.getFloat64(pointOffset + 8, true),
          );
          commands.push(
            `${pointIndex === start ? "M" : "L"}${coordinate(point.x)} ${coordinate(point.y)}`,
          );
        }

        if (commands.length > 2) paths.push(`${commands.join("")}Z`);
      }
    }

    recordOffset = recordEnd;
  }

  return paths;
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Natural Earth download failed (${response.status}).`);
}

const archive = unzipSync(new Uint8Array(await response.arrayBuffer()));
const shapefileEntry = Object.entries(archive).find(([name]) =>
  name.endsWith("ne_50m_land.shp"),
);
if (!shapefileEntry) throw new Error("Natural Earth land shapefile is missing.");

const paths = polygonPaths(shapefileEntry[1]);
if (paths.length === 0) throw new Error("Natural Earth land polygons are empty.");

const targetPath = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "public",
  "voice",
  "pronunciation-atlas-earth-equirectangular-v2.svg",
);
const output = `<!-- Generated by apps/web/scripts/generate-pronunciation-atlas-earth.mjs.
Source: Natural Earth 1:50m land, public domain.
Projection: equirectangular, longitude -180..180 and latitude 90..-90. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" preserveAspectRatio="none">
  <path fill="#fff" fill-rule="evenodd" d="${paths.join("")}"/>
</svg>
`;

writeFileSync(targetPath, output, "utf8");
console.log(`Wrote ${paths.length} land rings to ${targetPath}`);
